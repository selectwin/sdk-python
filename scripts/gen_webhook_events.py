"""Generate src/selectwin/webhook_events.py from the vendored core's event enum.

The core carries the authoritative event list as an enum
(``models/create_webhook_endpoint_body_events_item.py``). We emit the catalog
tuple + ``Literal`` types + a runtime guard, so the catalog auto-syncs with the
spec on every ``scripts/sync_core.py``.

Run: python scripts/gen_webhook_events.py
"""

from __future__ import annotations

import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
ENUM = REPO / "src" / "selectwin" / "_core" / "models" / "create_webhook_endpoint_body_events_item.py"
OUT = REPO / "src" / "selectwin" / "webhook_events.py"

# Canonical resource order for readable grouping; unknown groups append after.
GROUP_ORDER = [
    "transaction", "customer", "card", "subscription", "receivable",
    "wallet", "seller", "withdrawal", "webhook", "checkout",
]
# Group type-name overrides (avoid clashing with the master WebhookEventType).
GROUP_TYPE_NAME = {"webhook": "WebhookEndpointEventType"}


def group_type_name(group: str) -> str:
    return GROUP_TYPE_NAME.get(group, f"{group.capitalize()}EventType")


def main() -> None:
    src = ENUM.read_text(encoding="utf-8")
    values = re.findall(r'=\s*"([^"]+)"', src)
    if not values:
        raise SystemExit(f"no event values parsed from {ENUM}")

    # Group by first segment, ordering groups canonically then by first-seen.
    groups: dict[str, list[str]] = {}
    for v in values:
        groups.setdefault(v.split(".")[0], []).append(v)
    ordered_groups = [g for g in GROUP_ORDER if g in groups] + [g for g in groups if g not in GROUP_ORDER]

    ordered_values: list[str] = []
    for g in ordered_groups:
        ordered_values.extend(sorted(groups[g]))

    def literal(items: list[str]) -> str:
        return "Literal[\n" + "".join(f"    {v!r},\n" for v in items) + "]"

    lines = [
        '"""GENERATED by scripts/gen_webhook_events.py — DO NOT EDIT.',
        "",
        "Typed webhook Event Catalog derived from the spec's authoritative event enum",
        "(create_webhook_endpoint_body_events_item). Regenerate after scripts/sync_core.py.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import Tuple",
        "",
        "try:  # Python 3.8+ has Literal in typing; keep a typing_extensions fallback.",
        "    from typing import Literal",
        "except ImportError:  # pragma: no cover",
        "    from typing_extensions import Literal  # type: ignore",
        "",
        "#: Every webhook event type Selectwin can deliver (authoritative catalog).",
        "WEBHOOK_EVENT_TYPES: Tuple[str, ...] = (",
        *[f"    {v!r}," for v in ordered_values],
        ")",
        "",
        "#: Union of every `resource.action` webhook event type.",
        f"WebhookEventType = {literal(ordered_values)}",
        "",
    ]
    for g in ordered_groups:
        lines.append(f"#: `{g}.*` event types.")
        lines.append(f"{group_type_name(g)} = {literal(sorted(groups[g]))}")
        lines.append("")

    lines += [
        "_WEBHOOK_EVENT_TYPE_SET = frozenset(WEBHOOK_EVENT_TYPES)",
        "",
        "",
        "def is_webhook_event_type(value: object) -> bool:",
        '    """Runtime guard: is `value` one of the known webhook event types?"""',
        "    return isinstance(value, str) and value in _WEBHOOK_EVENT_TYPE_SET",
        "",
    ]

    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)} — {len(ordered_values)} event types, {len(ordered_groups)} groups")


if __name__ == "__main__":
    main()
